function numbered(items) {
  return items.map((t, i) => ({ text: `${i + 1}) ${t}${i === items.length - 1 ? '.' : ';'}`, align: 'both', indent: true }));
}

function spouseLine(sp) {
  return joinNonEmpty([sp.name, sp.birth_date && 'дата рождения: ' + fmtDate(sp.birth_date), sp.birth_place && 'место рождения: ' + sp.birth_place, sp.inn && 'ИНН ' + sp.inn, sp.snils && 'СНИЛС ' + sp.snils]);
}

// ---------- Оформление ----------

function signatureTable(c, date = '') {
  return { table: { cols: [1, 1], borders: false, size: 12, rows: [[
    { text: `${c.Role}${date ? '\n\n' + date : ''}` },
    { text: `____________________ ${c.auShort}`, align: 'right' },
  ]] } };
}

// Письмо: слева реквизиты отправителя и исходящий номер, справа адресат.
function letterBlocks(c, doc, { title, subtitle, body, attachments = [] }) {
  const sender = joinNonEmpty([
    c.Role,
    c.auName,
    `дело № ${c.caseNo}, должник: ${c.debShort}`,
    c.au.postal_address && 'Адрес для корреспонденции: ' + c.au.postal_address,
    joinNonEmpty([c.au.phone && 'тел. ' + c.au.phone, c.au.email && 'e-mail: ' + c.au.email]),
    '',
    `Исх. № ${doc.number || '____'} от ${doc.date ? fmtDate(doc.date) : '__.__.____'}`,
  ], '\n');
  const to = joinNonEmpty([doc.addressee || '[адресат]', doc.address], '\n');
  return [
    { table: { cols: [1, 1], borders: false, size: 11, rows: [[{ text: sender }, { text: to }]] } },
    { text: title, align: 'center', bold: true, before: 120, after: subtitle ? 0 : 120 },
    subtitle ? { text: subtitle, align: 'center', bold: true, after: 120 } : null,
    ...bodyBlocks(body),
    ...attachmentBlocks(attachments),
    { text: '', after: 120 },
    signatureTable(c),
  ];
}

// Документ в арбитражный суд: «шапка» справа, затем заголовок и текст.
function courtBlocks(c, doc, { title, subtitle, body, attachments = [] }) {
  const head = joinNonEmpty([
    `В ${c.court}`,
    c.p.court.address,
    '',
    `Дело № ${c.caseNo}`,
    c.judge && `Судья ${c.judge}`,
    '',
    `Заявитель: ${c.role} ${c.auName}`,
    c.auContacts,
    '',
    `Должник: ${c.debName}`,
    c.ident,
  ].map(x => (x === '' ? ' ' : x)), '\n');
  return [
    { text: head, align: 'left', left: 4536, indent: false, after: 200 },
    { text: title, align: 'center', bold: true, after: subtitle ? 0 : 120 },
    subtitle ? { text: subtitle, align: 'center', bold: true, after: 120 } : null,
    ...bodyBlocks(body),
    ...attachmentBlocks(attachments),
    { text: '', after: 120 },
    signatureTable(c, doc.date ? fmtDate(doc.date) : '«___» __________ 20__ г.'),
  ];
}

// Пустая строка разделяет абзацы. Строки внутри абзаца (пункты списка) — отдельные абзацы без отбивки,
// иначе Word растягивает пробелы в строке перед переносом.
function bodyBlocks(body) {
  const out = [];
  for (const block of String(body || '').split(/\n{2,}/).map(t => t.trim()).filter(Boolean)) {
    if (/^ПРОШУ:?$/i.test(block)) { out.push({ text: block, align: 'center', bold: true, before: 60, after: 60 }); continue; }
    const lines = block.split('\n').map(s => s.trim()).filter(Boolean);
    lines.forEach((line, i) => out.push({ text: line, align: 'both', indent: true, after: i === lines.length - 1 ? 60 : 0 }));
  }
  return out;
}

function attachmentBlocks(list) {
  const items = (Array.isArray(list) ? list : String(list || '').split('\n')).map(s => s.trim()).filter(Boolean);
  if (!items.length) return [];
  return [{ text: 'Приложение:', bold: true, before: 120, align: 'left' }, ...items.map((t, i) => ({ text: `${i + 1}. ${t.replace(/^\d+[.)]\s*/, '')}`, align: 'left' }))];
}

