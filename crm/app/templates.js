const ATTACH_ACT = 'Копия судебного акта о введении процедуры и утверждении арбитражного управляющего.';

function requestBody(c, items, { spouse, extra = [], intro = '' } = {}) {
  const what = [...items];
  if (spouse && c.info.fl) what.push(`аналогичные сведения в отношении супруга(и) должника — ${spouseLine(spouse)} (п. 7 ст. 213.9 Закона о банкротстве)`);
  return [
    c.intro + ' ' + c.auSentence,
    intro,
    `На основании ${c.basis} прошу в течение семи дней со дня получения настоящего запроса без взимания платы предоставить в отношении должника за период с ${c.periodFrom} по дату ответа следующие сведения:`,
    what.map((t, i) => `${i + 1}) ${t}${i === what.length - 1 ? '.' : ';'}`).join('\n'),
    ...extra,
    'Сведения, составляющие служебную, коммерческую и банковскую тайну, предоставляются арбитражному управляющему без предварительного обращения в арбитражный суд (п. 1 ст. 20.3 Закона о банкротстве).',
    c.answerTo,
  ].filter(Boolean).join('\n\n');
}

function req(key, title, items, more = {}) {
  return {
    group: 'requests', title: more.title || ADDRESSEE_LABELS[key] || title, addresseeKey: key, docTitle: more.docTitle || 'ЗАПРОС', subtitle: more.subtitle || '',
    spouseAware: more.spouseAware !== false,
    body: (c, x) => requestBody(c, typeof items === 'function' ? items(c) : items, { spouse: x.spouse, extra: more.extra ? more.extra(c) : [], intro: more.intro ? more.intro(c) : '' }),
    attachments: () => [ATTACH_ACT],
  };
}

