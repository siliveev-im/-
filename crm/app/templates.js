const cap = s => (s ? s[0].toUpperCase() + s.slice(1) : '');
const joinNonEmpty = (arr, sep = ', ') => arr.filter(Boolean).join(sep);

function courtGen(name) {
  return (name || 'Арбитражного суда [наименование]').replace(/^Арбитражный суд/, 'Арбитражного суда');
}

// «Силивеев Илья Михайлович» → «И. М. Силивеев»
function initials(full) {
  const [f, i, o] = String(full || '').trim().split(/\s+/);
  if (!f) return '';
  return joinNonEmpty([i && i[0] + '.', o && o[0] + '.', f], ' ');
}

