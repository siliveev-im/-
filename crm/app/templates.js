// Свой шаблон из Настроек: подстановки в фигурных скобках.
const PLACEHOLDERS = {
  'должник': c => c.debShort, 'должник_полностью': c => c.debName, 'идентификация': c => c.ident, 'суд': c => c.court,
  'дело': c => c.caseNo, 'судья': c => c.judge, 'процедура': c => c.info.nameGen, 'управляющий': c => c.role,
  'вводная': c => `${c.intro} ${c.auSentence}`, 'АУ': c => c.auName, 'АУ_кратко': c => c.auShort,
  'адрес_АУ': c => c.au.postal_address || '', 'основной_счёт': c => c.mainAccount, 'дата': () => fmtDate(todayISO()),
};

function fillPlaceholders(text, c) {
  return String(text || '').replace(/\{\{\s*([^}]+?)\s*\}\}/g, (m, k) => (PLACEHOLDERS[k] ? PLACEHOLDERS[k](c) : m));
}

// Все шаблоны с учётом своих из Настроек.
function allTemplates() {
  const own = {};
  for (const t of DATA.settings.doc_templates || []) {
    own['own:' + t.id] = {
      group: 'own', title: t.title || 'Без названия', kind: t.kind === 'court' ? 'court' : 'letter', docTitle: (t.doc_title || '').toUpperCase(),
      addressee: () => t.addressee || '', address: () => t.address || '', body: c => fillPlaceholders(t.body, c), attachments: () => String(t.attachments || '').split('\n'),
    };
  }
  return { ...TEMPLATES, ...own };
}

function addresseeFor(key) {
  const a = (DATA.settings.addressees || {})[key] || {};
  return { name: a.name || DEFAULT_ADDRESSEES[key] || '', address: a.address || '' };
}

// Новый черновик документа по шаблону.
function draftFromTemplate(p, key, extra = {}) {
  const t = allTemplates()[key];
  const c = docCtx(p);
  const addr = t.addresseeKey ? addresseeFor(t.addresseeKey) : null;
  return {
    id: uid(),
    template: key,
    title: t.title + (extra.titleSuffix || ''),
    heading: t.docTitle || '',
    subheading: t.subtitle || '',
    date: todayISO(),
    number: '',
    addressee: extra.addressee ?? (addr ? addr.name : t.addressee ? t.addressee(c) : ''),
    address: extra.address ?? (addr ? addr.address : t.address ? t.address(c) : ''),
    text: t.body(c, extra),
    attachments: (t.attachments ? t.attachments(c) : []).filter(Boolean).join('\n'),
    status: 'Черновик',
    in_report: (t.group === 'requests' || t.group === 'banks') && t.kind !== 'text',
    spouse_id: extra.spouse?.id || '',
  };
}

// Готовый файл Word по документу.
function documentBlocks(p, doc) {
  const t = allTemplates()[doc.template] || TEMPLATES.free;
  const c = docCtx(p);
  const parts = { title: doc.heading ?? t.docTitle ?? '', subtitle: doc.subheading ?? t.subtitle ?? '', body: doc.text, attachments: doc.attachments };
  if (t.kind === 'court') return courtBlocks(c, doc, parts);
  if (t.kind === 'text') return [{ text: parts.title, align: 'center', bold: true, after: 200 }, ...bodyBlocks(doc.text)];
  if (t.kind === 'act') return [{ text: parts.title, align: 'center', bold: true }, { text: parts.subtitle, align: 'center', bold: true, after: 200 }, ...bodyBlocks(doc.text)];
  return letterBlocks(c, doc, parts);
}
